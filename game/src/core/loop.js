/* ------------------------------------------------------------------ *
 *  프레임 콜백 레지스트리.
 *
 *  M0에서는 순서 없는 단일 리스트로 충분하다(등록된 게 램프 애니메이션
 *  하나뿐). M1에서 이동/카메라가 들어오면 입력→충돌→카메라 순서가
 *  중요해지므로, 그때 onFrame(fn, phase) 형태로 확장한다(현재 호출부는
 *  그대로 호환됨). 각 모듈은 자기 init()에서 여기 등록만 하고,
 *  main.js는 매 프레임 tick(dt) 한 번만 호출한다 — 레인이 늘어나도
 *  main.js가 커지지 않는 이유.
 * ------------------------------------------------------------------ */
const listeners = [];

export function onFrame(fn) {
  listeners.push(fn);
}

export function tick(dt) {
  for (const fn of listeners) fn(dt);
}
